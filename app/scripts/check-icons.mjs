// Icon names, three ways. Run in app/:
//   node scripts/check-icons.mjs          fail if a name the app can render is missing from src/ui/icon-manifest.ts, or the
//                                         manifest names an icon the font file has no ligature for
//   node scripts/check-icons.mjs --write  regenerate src/ui/icon-manifest.ts from the names found in src and sample data
//   node scripts/check-icons.mjs --font <file>   print the icon names a woff2 draws (to compare a download)
// App-owned. The font in public/fonts/material-symbols-rounded.woff2 is a subset: Google Fonts serves it for the
// manifest's names (see docs/plans/2026-11-19-production.md, PD8). A name outside it would draw as ligature text.
import fs from 'node:fs'
import path from 'node:path'
import zlib from 'node:zlib'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const MANIFEST = path.join(root, 'src/ui/icon-manifest.ts')
const FONT = path.join(root, 'public/fonts/material-symbols-rounded.woff2')

// Names that reach <Icon> through a tuple or a record, where no `icon` key or attribute names them, and that are plain
// words (a name with an underscore is found by its shape). Every one must still appear as a string in src, or this
// check fails, so the list can't go stale. A new plain-word name passed this way is caught at run time instead: the
// Icon draws the fallback glyph and warns in dev.
const TUPLE_NAMES = ['badge', 'build', 'code', 'description', 'group', 'hub', 'image', 'psychology', 'sort', 'stacks', 'stairs', 'straighten', 'person', 'schedule', 'history', 'tune', 'savings', 'work', 'campaign', 'logout', 'notifications', 'neurology']
// Always drawn by the fallback.
const FALLBACK = 'circle'

const LIT = /["'`]([a-z][a-z0-9_]*)["'`]/g
const lits = (s) => [...s.matchAll(LIT)].map(m => m[1])
// The names an expression can return: a `x === 'dark'` test isn't one.
const results = (s) => lits(s.replace(/[!=]==?\s*["'`][^"'`]*["'`]/g, ''))

function walk(dir, ok, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) walk(p, ok, out)
    else if (ok(p)) out.push(p)
  }
  return out
}

/** Where a name is spelled out: Icon `name`, an `icon` attribute or key, a name with an underscore, a sample-data `icon`. */
function usedNames() {
  const used = new Map() // name -> first file
  const add = (n, f) => { if (!used.has(n)) used.set(n, path.relative(root, f)) }
  const srcFiles = walk(path.join(root, 'src'), p => /\.(tsx?|json)$/.test(p) && !/\.test\.tsx?$/.test(p) && p !== MANIFEST)
  for (const f of srcFiles) {
    const s = fs.readFileSync(f, 'utf8')
    if (f.endsWith('.json')) {
      for (const m of s.matchAll(/"icon"\s*:\s*"([^"]+)"/g)) add(m[1], f)
      continue
    }
    for (const m of s.matchAll(/<Icon\b[^>]*?\bname=(?:"([^"]+)"|\{([^}]*)\})/g)) (m[1] ? [m[1]] : results(m[2])).forEach(n => add(n, f))
    for (const m of s.matchAll(/\bicon=(?:"([^"]+)"|\{([^}]*)\})/g)) (m[1] ? [m[1]] : results(m[2])).forEach(n => add(n, f))
    for (const m of s.matchAll(/\bicon:\s*([^,}\n;]+)/g)) results(m[1]).forEach(n => add(n, f))
    for (const n of lits(s)) if (n.includes('_') && /^[a-z]+(_[a-z0-9]+)+$/.test(n)) add(n, f)
  }
  const strings = new Set(srcFiles.flatMap(f => (f.endsWith('.json') ? [] : lits(fs.readFileSync(f, 'utf8')))))
  const stale = TUPLE_NAMES.filter(n => !strings.has(n))
  for (const n of TUPLE_NAMES) add(n, 'scripts/check-icons.mjs')
  const base = fs.readFileSync(path.join(root, 'src/components/ui/icon-names.ts'), 'utf8')
  lits(base.slice(0, base.indexOf(']'))).forEach(n => add(n, path.join(root, 'src/components/ui/icon-names.ts')))
  add(FALLBACK, 'scripts/check-icons.mjs')
  return { used, stale }
}

function readManifest() {
  if (!fs.existsSync(MANIFEST)) return []
  const s = fs.readFileSync(MANIFEST, 'utf8')
  return lits(s.slice(s.indexOf('['), s.indexOf(']')))
}

function writeManifest(names) {
  const body = `// Generated by scripts/check-icons.mjs --write: every Material Symbols name the app can draw, sorted. Don't edit by hand.
// The font (public/fonts/material-symbols-rounded.woff2) is a subset for exactly these names, so a name outside the list
// would draw as ligature text. \`IconName\` is the union; the Icon in ./index.tsx draws a fallback for any other string.
export const ICON_NAMES = [
${names.map(n => `  '${n}',`).join('\n')}
] as const

export type IconName = (typeof ICON_NAMES)[number]
`
  fs.writeFileSync(MANIFEST, body)
}

// ---- A woff2 reader, just enough to list the names the font's ligatures spell (GSUB type 4 + cmap) ----
const TAGS = ['cmap','head','hhea','hmtx','maxp','name','OS/2','post','cvt ','fpgm','glyf','loca','prep','CFF ','VORG','EBDT','EBLC','gasp','hdmx','kern','LTSH','PCLT','VDMX','vhea','vmtx','BASE','GDEF','GPOS','GSUB','EBSC','JSTF','MATH','CBDT','CBLC','COLR','CPAL','SVG ','sbix','acnt','avar','bdat','bloc','bsln','cvar','fdsc','feat','fmtx','fvar','gvar','hsty','just','lcar','mort','morx','opbd','prop','trak','Zapf','Silf','Glat','Gloc','Feat','Sill']

function fontNames(file) {
  const b = fs.readFileSync(file)
  if (b.toString('latin1', 0, 4) !== 'wOF2') throw new Error(`${file} is not a woff2 file`)
  const n = b.readUInt16BE(12), compressed = b.readUInt32BE(20)
  let p = 48
  const base128 = () => { let v = 0; for (let i = 0; i < 5; i++) { const c = b[p++]; v = v * 128 + (c & 127); if (!(c & 128)) return v } throw new Error('bad UIntBase128') }
  const tables = {}
  let off = 0
  for (let i = 0; i < n; i++) {
    const flags = b[p++], idx = flags & 63, ver = flags >> 6
    const tag = idx === 63 ? (p += 4, b.toString('latin1', p - 4, p)) : TAGS[idx]
    const orig = base128()
    const transformed = tag === 'glyf' || tag === 'loca' ? ver === 0 : ver !== 0
    const len = transformed ? base128() : orig
    tables[tag] = { off, len }
    off += len
  }
  const d = zlib.brotliDecompressSync(b.subarray(p, p + compressed))
  const t = (tag) => { if (!tables[tag]) throw new Error(`font has no ${tag} table`); return d.subarray(tables[tag].off, tables[tag].off + tables[tag].len) }

  // cmap: glyph id -> character
  const cmap = t('cmap'), gidChar = new Map()
  for (let i = 0; i < cmap.readUInt16BE(2); i++) {
    const plat = cmap.readUInt16BE(4 + i * 8), enc = cmap.readUInt16BE(6 + i * 8), o = cmap.readUInt32BE(8 + i * 8)
    if (!((plat === 3 && (enc === 1 || enc === 10)) || plat === 0)) continue
    const fmt = cmap.readUInt16BE(o)
    if (fmt === 12) {
      for (let g = 0, ng = cmap.readUInt32BE(o + 12); g < ng; g++) {
        const [s, e, id] = [0, 4, 8].map(k => cmap.readUInt32BE(o + 16 + g * 12 + k))
        for (let c = s; c <= e; c++) gidChar.set(id + c - s, String.fromCodePoint(c))
      }
    } else if (fmt === 4) {
      const segs = cmap.readUInt16BE(o + 6) / 2
      for (let g = 0; g < segs; g++) {
        const end = cmap.readUInt16BE(o + 14 + g * 2), start = cmap.readUInt16BE(o + 16 + segs * 2 + g * 2)
        const delta = cmap.readUInt16BE(o + 16 + segs * 4 + g * 2), ro = cmap.readUInt16BE(o + 16 + segs * 6 + g * 2)
        for (let c = start; c <= end && c < 0xffff; c++) {
          let gid = ro === 0 ? (c + delta) & 0xffff : cmap.readUInt16BE(o + 16 + segs * 6 + g * 2 + ro + (c - start) * 2)
          if (gid && ro) gid = (gid + delta) & 0xffff
          if (gid) gidChar.set(gid, String.fromCodePoint(c))
        }
      }
    }
  }
  if (!gidChar.size) throw new Error('could not read the font cmap')

  // GSUB: every type 4 (ligature) lookup, also behind an extension (type 7)
  const g = t('GSUB'), out = new Set()
  const coverage = (o) => {
    const fmt = g.readUInt16BE(o), cnt = g.readUInt16BE(o + 2), r = []
    if (fmt === 1) for (let i = 0; i < cnt; i++) r.push(g.readUInt16BE(o + 4 + i * 2))
    else for (let i = 0; i < cnt; i++) { const s = g.readUInt16BE(o + 4 + i * 6), e = g.readUInt16BE(o + 6 + i * 6); for (let x = s; x <= e; x++) r.push(x) }
    return r
  }
  const llOff = g.readUInt16BE(8)
  const count = g.readUInt16BE(llOff)
  for (let i = 0; i < count; i++) {
    const lo = llOff + g.readUInt16BE(llOff + 2 + i * 2)
    let type = g.readUInt16BE(lo)
    for (let s = 0, sc = g.readUInt16BE(lo + 4); s < sc; s++) {
      let so = lo + g.readUInt16BE(lo + 6 + s * 2)
      if (type === 7) { if (g.readUInt16BE(so + 2) !== 4) continue; so += g.readUInt32BE(so + 4) } else if (type !== 4) continue
      const cov = coverage(so + g.readUInt16BE(so + 2))
      for (let k = 0, ns = g.readUInt16BE(so + 4); k < ns; k++) {
        const set = so + g.readUInt16BE(so + 6 + k * 2)
        for (let j = 0, nl = g.readUInt16BE(set); j < nl; j++) {
          const lg = set + g.readUInt16BE(set + 2 + j * 2), nc = g.readUInt16BE(lg + 2)
          const gl = [cov[k]]
          for (let c = 0; c < nc - 1; c++) gl.push(g.readUInt16BE(lg + 4 + c * 2))
          const name = gl.map(x => gidChar.get(x) ?? '?').join('')
          if (/^[a-z][a-z0-9_]*$/.test(name)) out.add(name)
        }
      }
    }
  }
  return out
}

// ---- main ----
const argv = process.argv.slice(2)
if (argv[0] === '--font') { console.log([...fontNames(argv[1])].sort().join('\n')); process.exit(0) }

const { used, stale } = usedNames()
if (argv[0] === '--write') {
  const names = [...used.keys()].sort()
  writeManifest(names)
  console.log(`check-icons: wrote ${names.length} names to ${path.relative(root, MANIFEST)}`)
  process.exit(0)
}

const manifest = new Set(readManifest())
const problems = []
for (const n of stale) problems.push(`"${n}" is in TUPLE_NAMES (scripts/check-icons.mjs) but no longer appears in src. Remove it.`)
for (const [n, f] of used) if (!manifest.has(n)) problems.push(`"${n}" (${f}) is not in src/ui/icon-manifest.ts. Run: node scripts/check-icons.mjs --write, then re-download the font subset.`)
const inFont = fontNames(FONT)
for (const n of manifest) if (!inFont.has(n)) problems.push(`"${n}" is in the manifest but the font has no ligature for it. Re-download the subset for the manifest's names.`)
if (problems.length) { console.error('check-icons failed:\n' + problems.map(p => '  ' + p).join('\n')); process.exit(1) }
console.log(`check-icons: ${manifest.size} names in the manifest, all used names covered, all in the font (${inFont.size} ligatures).`)
